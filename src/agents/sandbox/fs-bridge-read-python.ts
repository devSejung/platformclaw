/** Descriptor-pinned regular-file reads shared by filesystem tools and attachment export. */
export const SANDBOX_READ_FILE_PYTHON = [
  "def read_file_impl(parent_fd, basename, max_bytes, require_owner=False):",
  "    require_owner = require_owner or owned_parent(parent_fd)",
  "    if max_bytes is not None and max_bytes < 0:",
  "        raise OSError(errno.EINVAL, 'read limit must be non-negative', basename)",
  // Temp files share a runtime with other accounts. Check the opened inode;
  // nonblocking open lets us reject FIFOs before waiting for their writer.
  "    read_flags = READ_FLAGS | (os.O_NONBLOCK if require_owner else 0)",
  "    file_fd = os.open(basename, read_flags, dir_fd=parent_fd)",
  "    try:",
  "        file_stat = os.fstat(file_fd)",
  "        if not stat.S_ISREG(file_stat.st_mode):",
  "            raise OSError(errno.EPERM, 'only regular files are allowed', basename)",
  "        if file_stat.st_nlink > 1:",
  "            raise OSError(errno.EPERM, 'hardlinked file is not allowed', basename)",
  "        if require_owner and (file_stat.st_uid != os.geteuid() or file_stat.st_nlink != 1):",
  "            raise OSError(errno.EPERM, 'outbound temp file must belong to the runtime account', basename)",
  "        if max_bytes is not None and file_stat.st_size > max_bytes:",
  "            raise OSError(errno.EFBIG, 'file exceeds bounded read limit', basename)",
  "        bytes_read = 0",
  "        while True:",
  "            read_size = 65536 if max_bytes is None else min(65536, max_bytes - bytes_read + 1)",
  "            chunk = os.read(file_fd, read_size)",
  "            if not chunk:",
  "                break",
  "            bytes_read += len(chunk)",
  "            if max_bytes is not None and bytes_read > max_bytes:",
  "                raise OSError(errno.EFBIG, 'file exceeds bounded read limit', basename)",
  "            write_all(1, chunk)",
  "        if require_owner:",
  "            final_stat = os.fstat(file_fd)",
  "            if not same_identity(entry_identity(file_stat), final_stat) or final_stat.st_nlink != 1 or final_stat.st_uid != os.geteuid():",
  "                raise OSError(errno.ESTALE, 'outbound temp file changed during read', basename)",
  "    finally:",
  "        os.close(file_fd)",
  "",
].join("\n");
