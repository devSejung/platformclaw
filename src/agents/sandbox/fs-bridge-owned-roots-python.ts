  "    if not owned_parent(parent_fd):",
  "        return",
  "    try:",
  "        value = os.stat(basename, dir_fd=parent_fd, follow_symlinks=False)",
  "    except FileNotFoundError:",
  "        if allow_missing:",
  "            return",
  "        raise",
